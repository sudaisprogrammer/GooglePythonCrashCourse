#tuple in python
#tuples are immutable data types in python, which means that once a tuple is created,  it cannot be modified. Tuples are defined using parentheses () and can contain elements of different data types, including other tuples.

frutis = ("apple","banana","cherry","kiwi","mango")
print(frutis)

print(frutis.count("apple")) #print number of times "apple" appears in the tuple
print(frutis.index("kiwi")) #print the index of "kiwi" in the tuple